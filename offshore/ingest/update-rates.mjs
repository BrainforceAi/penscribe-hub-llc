#!/usr/bin/env node
/** Refreshes data/rates.js (base currency -> every currency) from a free public endpoint. Run daily. */
import { writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../data");
const courses = await readFile(path.join(dir, "courses.js"), "utf8");
const base = /COURSE_BASE_CURRENCY = "(\w+)"/.exec(courses)?.[1] || "THB";
const res = await fetch(`https://open.er-api.com/v6/latest/${base}`);
if (!res.ok) throw new Error("Rates HTTP " + res.status);
const j = await res.json();
if (j.result !== "success") throw new Error("Rates API said: " + JSON.stringify(j).slice(0, 200));
await writeFile(path.join(dir, "rates.js"), `/* Generated by ingest/update-rates.mjs. Source: ${j.provider || "open.er-api.com"} */\nwindow.RATES = ${JSON.stringify({ base, asOf: new Date(j.time_last_update_utc).toISOString().slice(0, 10), rates: j.rates })};\n`);
console.log(`Rates for 1 ${base}: USD ${j.rates.USD}, EUR ${j.rates.EUR}, NGN ${j.rates.NGN}; ${Object.keys(j.rates).length} currencies, as of ${j.time_last_update_utc}`);
