#!/usr/bin/env node
/**
 * Pulls the partner's full course catalogue (public WooCommerce Store API) into data/courses.js.
 * Run:  node offshore/ingest/sync-courses.mjs   (re-run daily/weekly to keep courses and base prices current)
 * Base prices are stored in the partner's currency (THB) and converted for each visitor in the browser.
 * Only republish with the partner's written permission.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const SOURCE = process.env.COURSE_SOURCE || "https://mogit.org/wp-json/wc/store/v1/products?per_page=100";
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../data/courses.js");

const NAMED = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", rsquo: "’", lsquo: "‘", ldquo: "“", rdquo: "”", ndash: "–", mdash: "—", hellip: "…" };
const decode = s => s.replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n)).replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16))).replace(/&([a-z]+);/gi, (m, n) => NAMED[n.toLowerCase()] ?? m);
const esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const ALLOWED = new Set(["p", "ul", "ol", "li", "strong", "b", "em", "i", "br", "h4"]);
const plain = s => decode(String(s || "").replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
// keep only a safe subset of tags (no attributes); everything else becomes text
function sanitize(html) {
  let s = decode(html).replace(/\[\/?[a-z_0-9]+[^\]]*\]/gi, "").replace(/ /g, " ");
  const parts = s.split(/(<\/?[a-zA-Z0-9]+[^>]*>)/);
  s = parts.map(p => { const m = /^<(\/?)([a-zA-Z0-9]+)[^>]*>$/.exec(p); if (!m) return esc(p); const t = m[2].toLowerCase(); return ALLOWED.has(t) ? `<${m[1]}${t}>` : ""; }).join("");
  return s.replace(/<p>\s*<\/p>/g, "").replace(/(<br>\s*){3,}/g, "<br><br>").replace(/\s+/g, " ").replace(/> </g, "><").replace(/^(\s*<\/(p|li|ul|ol)>)+/, "").replace(/(<(p|li|ul|ol)>\s*)+$/, "").replace(/<p>\s*<\/p>/g, "").trim();
}
const QUOTE = '["“”″‶]';
function sections(descRaw) {
  const desc = decode(descRaw), map = {};
  for (const m of desc.matchAll(/\[et_pb_accordion_item([^\]]*)\]([\s\S]*?)\[\/et_pb_accordion_item\]/g)) {
    const t = new RegExp("title=" + QUOTE + "(.*?)" + QUOTE).exec(m[1]); if (!t) continue;
    map[t[1].trim().toLowerCase()] = sanitize(m[2]);
  }
  const rest = desc.replace(/\[et_pb_accordion[^\]]*\][\s\S]*?\[\/et_pb_accordion\]/g, "").replace(/\[\/?[a-z_0-9]+[^\]]*\]/gi, " ");
  return { map, approval: (/Approved by ([^<\[\n]*?)(?:\s*Price not|\s*\(|$|<)/i.exec(plain(rest)) || [])[1]?.trim() || "", note: (/\((This particular[^)]*)\)/.exec(plain(rest)) || [])[1] || "" };
}
const res = await fetch(SOURCE, { headers: { "User-Agent": "Mozilla/5.0 (catalogue sync)" } });
if (!res.ok) throw new Error("Source returned HTTP " + res.status);
const raw = await res.json();
const courses = raw.map(p => {
  const { map, approval, note } = sections(p.description);
  const sched = map["schedule, class size, locations"] || "";
  const sp = plain(sched);
  const part = re => (re.exec(sp) || [])[1]?.trim().replace(/[.\s]+$/, "") || "";
  const ov = plain(map["course overview"] || "");
  const summary = (ov.match(/^(.{80,260}?[.!?])(\s|$)/) || [null, ov.length > 220 ? ov.slice(0, 220).replace(/\s+\S*$/, "") + "…" : ov])[1];
  const aka = plain(p.short_description).replace(/^.*?\(such as\):\s*/i, "").replace(/^This course can call by other name\s*/i, "");
  return {
    id: p.id, slug: p.slug, sku: p.sku || "", name: plain(p.name), category: plain(p.categories?.[0]?.name || "Other"),
    approval, note, summary, aka,
    priceTHB: Number(p.prices.price) / Math.pow(10, p.prices.currency_minor_unit ?? 2),
    overview: map["course overview"] || "", who: map["who should attend"] || "",
    aims: map["aims & objectives"] || map["aims and objectives"] || "", demands: map["physical and stressful demands"] || "",
    prereq: map["prerequisites"] || "", outline: map["course outline"] || "", certification: map["certification"] || "",
    competency: map["competency"] || "", included: map["included"] || "",
    when: part(/(?:Weekly Schedule|Daily|Schedule):\s*(.*?)\s*Min\/Max/i), classSize: part(/Min\/Max Class Size:\s*(.*?)\s*Locations:/i), locations: part(/Locations:\s*(.*)$/i),
    schedule: sp.replace(/\s*(Min\/Max Class Size)/i, " · $1").replace(/\s*(Locations:)/i, " · $1")
  };
});
courses.sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));
const base = raw[0]?.prices?.currency_code;
await writeFile(out, `/* Generated by ingest/sync-courses.mjs on ${new Date().toISOString()}. Base price currency: ${base}. */\nwindow.COURSE_BASE_CURRENCY = ${JSON.stringify(base)};\nwindow.COURSES = ${JSON.stringify(courses)};\n`);
const miss = k => courses.filter(c => !c[k]).length;
console.log(`Wrote ${courses.length} courses (${base}).`, { noOverview: miss("overview"), noWho: miss("who"), noOutline: miss("outline"), noCert: miss("certification"), noSchedule: miss("schedule"), noApproval: miss("approval") });
console.log([...new Set(courses.map(c => c.category))]);
